import fs from 'node:fs';
import { geoArea, geoNaturalEarth1, geoPath } from '../angular/node_modules/d3-geo/src/index.js';
import { feature, neighbors } from '../angular/node_modules/topojson-client/src/index.js';

const topology = JSON.parse(fs.readFileSync(new URL('./data/world-atlas-50m.json', import.meta.url)));
const countries = feature(topology, topology.objects.countries).features;
const projection = geoNaturalEarth1().fitExtent([[14, 14], [946, 486]], { type: 'Sphere' });
const path = geoPath(projection).digits(1);
const fallback = { FRA: 'FR', NOR: 'NO', KOS: 'XK', TWN: 'TW' };
const geometries = topology.objects.countries.geometries;
const countryCodes = geometries.map(geometry => {
  const properties = geometry.properties ?? {};
  return /^[A-Z]{2}$/.test(properties.isoA2) ? properties.isoA2 : fallback[properties.adm0A3] ?? null;
});
const adjacent = neighbors(geometries);
const focusGeometry = country => {
  if (country.geometry.type !== 'MultiPolygon') return country;
  const polygons = country.geometry.coordinates.map(coordinates => ({ type: 'Polygon', coordinates }));
  return polygons.reduce((largest, polygon) => geoArea(polygon) > geoArea(largest) ? polygon : largest);
};
const result = countries.map((country, index) => {
  const properties = country.properties ?? {};
  const rawCode = properties.isoA2;
  const code = /^[A-Z]{2}$/.test(rawCode) ? rawCode : fallback[properties.adm0A3] ?? null;
  const bounds = path.bounds(focusGeometry(country));
  const centroid = path.centroid(country);
  return { code, name: properties.name, path: path(country), bounds: bounds.flat().map(n => +n.toFixed(2)),
    center: centroid.map(n => +n.toFixed(2)), neighbors: adjacent[index].map(i => countryCodes[i]).filter(Boolean) };
}).filter(country => country.path && country.name);
const output = `// Generated by scripts/build-world-map.mjs from @cublya/world-atlas 3.0.0-beta.2 (Natural Earth 5.1.2).\n` +
  `export interface GoodWorldCountry { code: string | null; name: string; path: string; bounds: [number, number, number, number]; center: [number, number]; neighbors: string[] }\n` +
  `export const GOOD_WORLD_COUNTRIES: readonly GoodWorldCountry[] = ${JSON.stringify(result)};\n`;
const destination = new URL('../angular/projects/goodui/src/lib/world-map-data.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (fs.readFileSync(destination, 'utf8') !== output) throw new Error('World map geometry is stale. Run npm run map:generate.');
  console.log(`Checked ${result.length} country paths`);
} else {
  fs.writeFileSync(destination, output);
  console.log(`Generated ${result.length} country paths (${Buffer.byteLength(output)} bytes)`);
}
